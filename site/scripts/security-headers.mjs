import { createHash } from 'node:crypto';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';

// Hash the exact exported HTML, including the framework's hydration scripts.
// Regenerate and deploy this snippet together with every static build.
const root = new URL('../dist/client/', import.meta.url);
const hashes = new Set();
let pages = 0;
async function visit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = new URL(entry.name + (entry.isDirectory() ? '/' : ''), directory);
    if (entry.isDirectory()) await visit(path);
    else if (entry.name.endsWith('.html')) {
      pages++;
      const html = await readFile(path, 'utf8');
      for (const [, attributes, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
        if (!/\bsrc\s*=/i.test(attributes) && body.trim()) {
          hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
        }
      }
    }
  }
}
await visit(root);
if (!pages) throw new Error('No exported HTML found');
const policy = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort((a, b) => a.localeCompare(b)).join(' ')}`,
  "script-src-attr 'none'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');
const headers = {
  'Content-Security-Policy': policy,
  'Strict-Transport-Security': 'max-age=31536000',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
};
const output = new URL('../dist/deploy/', import.meta.url);
await mkdir(output, { recursive: true });
await writeFile(new URL('seikalp-security.conf', output),
  '# Generated by npm run build:vps. Do not edit.\n' +
  Object.entries(headers).map(([name, value]) => `add_header ${name} "${value}" always;\n`).join(''));
console.log(`Generated security headers for ${pages} pages (${hashes.size} script hashes).`);
